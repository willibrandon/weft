namespace Weft.Core;

/// <summary>
/// A cardinal direction used for focus movement and resizing.
/// </summary>
public enum LayoutDirection
{
    /// <summary>
    /// Toward smaller columns.
    /// </summary>
    Left,

    /// <summary>
    /// Toward larger columns.
    /// </summary>
    Right,

    /// <summary>
    /// Toward smaller rows.
    /// </summary>
    Up,

    /// <summary>
    /// Toward larger rows.
    /// </summary>
    Down
}
