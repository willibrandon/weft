namespace Weft.Core;

/// <summary>
/// The direction in which a layout split arranges its children.
/// </summary>
public enum SplitOrientation
{
    /// <summary>
    /// Children sit side by side from left to right.
    /// </summary>
    LeftRight,

    /// <summary>
    /// Children stack from top to bottom.
    /// </summary>
    TopBottom
}
